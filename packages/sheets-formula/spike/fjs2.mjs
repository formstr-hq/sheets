import * as fjs from "@formulajs/formulajs";
const show = (label, fn) => { try { const v = fn(); console.log(label.padEnd(30), v instanceof Error ? `Error(${v.message})` : v instanceof Date ? `Date(${v.toISOString()})` : JSON.stringify(v)); } catch (e) { console.log(label.padEnd(30), "THROWS", e.message); } };
show("YEAR(45000)", () => fjs.YEAR(45000));
show("MONTH(45000)", () => fjs.MONTH(45000));
show("EDATE(45000,1)", () => fjs.EDATE(45000, 1));
show("WEEKDAY(45000)", () => fjs.WEEKDAY(45000));
show("DAYS(45010,45000)", () => fjs.DAYS(45010, 45000));
show("TODAY() type", () => typeof fjs.TODAY());
show("SUM err in range", () => fjs.SUM([[1, new Error("#DIV/0!")]]));
show("NA()", () => fjs.NA());
show("IFERROR(err,5)", () => fjs.IFERROR(new Error("#DIV/0!"), 5));
show("ISERROR(err)", () => fjs.ISERROR(new Error("#N/A")));
show("AVERAGE([[1,'x',3]])", () => fjs.AVERAGE([[1, "x", 3]]));
show("MAX([[]])", () => fjs.MAX([[]]));
show("LEN('héllo')", () => fjs.LEN("héllo"));
show("ROUND(2.5,0)", () => fjs.ROUND(2.5, 0));
show("CONCAT('a',1)", () => fjs.CONCAT("a", 1));
show("SUMIF", () => fjs.SUMIF([[1], [2], [3]], ">1", [[10], [20], [30]]));
show("INDEX", () => fjs.INDEX([[1, 2], [3, 4]], 2, 1));
show("MATCH", () => fjs.MATCH(3, [[1], [2], [3]], 0));
console.log("DIVIDE?", typeof fjs.DIVIDE, "ADD?", typeof fjs.ADD, "IFERROR", typeof fjs.IFERROR);
